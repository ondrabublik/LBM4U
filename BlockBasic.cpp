BlockBasic::BlockBasic(bool isFirst, Block** blocks, int nBlock, int nBlockMax, int* blockMap, int nBi, int nBj, int nBk, int indBlock, int coarseLevel, int* indAll, int* indIn, int* indBound, bool mrtModel, bool isTauVariable, int nf, int* ex, int* ey, int* ez, double* w, int* opp, int ni, int nj, int nk, unordered_map<string, string> par) {
	this->blocks = blocks;
	this->nBlock = nBlock;
	this->nBlockMax = nBlockMax;
	this->blockMap = blockMap;
	this->mrtModel = mrtModel;
	this->nf = nf;
	this->ex = ex;
	this->ey = ey;
	this->ez = ez;
	this->w = w;
	this->opp = opp;
	this->nBi = nBi;
	this->nBj = nBj;
	this->nBk = nBk;
	this->indBlock = indBlock;
	this->coarseLevel = coarseLevel;
	this->indIn = indIn;
	this->indBound = indBound;
	this->indAll = indAll;
	this->ni = coarseLevel * ni;
	this->nj = coarseLevel * nj;
	this->nk = coarseLevel * nk;
	xPeriodicity = (stoi(par["xPeriodicity"]) ? true : false);
	nAll = ni * nj * nk;
	nIn = (ni - 2) * (nj - 2) * (nk - 2);
	nBound = nAll - nIn;

	Cu = stod(par["uMax"]) / 0.1;
	Ch = stod(par["H"]) / this->ni;
	Ct = Ch / Cu;
	Cp = stod(par["density"]) / 3 * Cu * Cu;
	Crho = stod(par["density"]);
	Cvis = Ch * Ch / Ct;
	vLB = stod(par["vKin"]) / Cvis;
	Cf = Ch / (Ct * Ct);
	tau = 1.0 / 2 + 3 * vLB;
	G = new double[3]{
		getParDouble("gx",par, false, 0) / Cf, getParDouble("gy",par, false, 0) / Cf, getParDouble("gz",par, false, 0) / Cf
	}; //gravity

	rho0 = 0.0;   //0 == normal, 1 == special treatment for higher precision

	int ntot = ni * nj * nk;
	boundary = new bool[ntot];
	fc = new double[ntot * nf];
	fcOld = new double[ntot * nf];
	f = new double[ntot * nf];
	Rho = new double[ntot];
	dRho = new double[ntot];
	U = new double[ntot];
	V = new double[ntot];
	W = new double[ntot];
	wallDistance = new double[ntot];
	wallDistanceGradient = new double[3 * ntot];
	wallDistancePolynome = new double[8 * ntot];

	if (mrtModel) {
		defineMRTmatrix();
	}

	if (isFirst) {
		cout << "tau = " << 1.0 / 2 + 3 * vLB / Cvis << endl;
	}
}

