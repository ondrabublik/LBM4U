void BlockBasic::collision() {
	double* bodyForce = new double[nf];
	double* feq = new double[nf];

	if (mrtModel) {
		for (int i = 0; i < nAll; i++) {
			int ind = indAll[i];
			if (!boundary[ind]) {
				for (int p = 0; p < nf; p++) { // vypocet equilibria
					bodyForce[p] = w[p] * (Rho[ind] * (ex[p] * G[0] + ey[p] * G[1] + ez[p] * G[2]) - rho0);
					double x = ex[p] * U[ind] + ey[p] * V[ind] + ez[p] * W[ind];
					double u2 = U[ind] * U[ind] + V[ind] * V[ind] + W[ind] * W[ind];
					feq[p] = w[p] * (Rho[ind] * (3.0 * x + 9.0 / 2.0 * x * x - 3.0 / 2.0 * u2) + dRho[ind]);
				}
				for (int p = 0; p < nf; p++) {
					double sum = 0;
					int pind = nf * ind + p;
					fcOld[pind] = fc[pind];
					for (int q = 0; q < nf; q++) {
						int qind = nf * ind + q;
						sum += T[nf * p + q] * (f[qind] - feq[q]);
					}
					fc[pind] = f[pind] - sum + bodyForce[p];
				}
			}
		}
	}
	else {
		for (int i = 0; i < nAll; i++) {
			int ind = indAll[i];
			if (!boundary[ind]) {
				equilibrium(feq, Rho[ind], dRho[ind], U[ind], V[ind], W[ind]);
				for (int p = 0; p < nf; p++) {
					int pind = nf * ind + p;
					fcOld[pind] = fc[pind];
					double bodyForce = w[p] * (Rho[ind] * (ex[p] * G[0] + ey[p] * G[1] + ez[p] * G[2]) - rho0);
					fc[pind] = f[pind] - 1.0 / tau * (f[pind] - feq[p]) + bodyForce;
				}
			}
		}
	}
	delete[] bodyForce;
	delete[] feq;
}

void BlockBasic::propagation() {
	for (int i = 0; i < nIn; i++) {
		int ind = indIn[i];
		if (!boundary[ind]) {
			for (int p = 0; p < nf; p++) {
				int indShift = ind + (ni * nj) * ez[p] + ni * ey[p] + ex[p];
				if (!boundary[indShift]) {
					f[nf * ind + opp[p]] = fc[nf * indShift + opp[p]];
				}
				else {
					f[nf * ind + opp[p]] = fc[nf * ind + p];
				}
			}
		}
	}

	for (int i = 0; i < nBound; i++) {
		int ind = indBound[i];

		int k = ind / (ni * nj);

		if (!boundary[ind]) {
			for (int p = 0; p < nf; p++) {
				int indShift = shift[nAll * p + ind];
				int indBlockShift = bShift[nAll * p + ind];
				if (indBlockShift > -1 && indBlockShift < nBlockMax && blocks[indBlockShift]) {
					if (!blocks[indBlockShift]->boundary[indShift]) {
						f[nf * ind + opp[p]] = blocks[indBlockShift]->fc[nf * indShift + opp[p]];
					}
					else {
						f[nf * ind + opp[p]] = fc[nf * ind + p];
					}
				}
				else {
					f[nf * ind + opp[p]] = fc[nf * ind + p];
				}
			}
		}
	}
}

void BlockBasic::makro() {
	for (int i = 0; i < nAll; i++) {
		int ind = indAll[i];
		if (!boundary[ind]) {
			dRho[ind] = 0;
			U[ind] = 0;
			V[ind] = 0;
			W[ind] = 0;
			for (int p = 0; p < nf; p++) {
				double fVal = f[nf * ind + p];
				dRho[ind] += fVal;
				U[ind] += ex[p] * fVal;
				V[ind] += ey[p] * fVal;
				W[ind] += ez[p] * fVal;
			}
			Rho[ind] = dRho[ind] + rho0;
			U[ind] /= Rho[ind];
			V[ind] /= Rho[ind];
			W[ind] /= Rho[ind];
		}
		else {
			Rho[ind] = 1;
			dRho[ind] = Rho[ind] - rho0;
			U[ind] = 0;
			V[ind] = 0;
			W[ind] = 0;

		}
	}
}

void BlockBasic::initZeroCondition() {
	for (int i = 0; i < nAll; i++) {
		int ind = indAll[i];
		Rho[ind] = 1;
		dRho[ind] = Rho[ind] - rho0;
		U[ind] = 0;
		V[ind] = 0;
		W[ind] = 0;

		for (int p = 0; p < nf; p++) {
			double x = ex[p] * U[ind] + ey[p] * V[ind] + ez[p] * W[ind];
			double u2 = U[ind] * U[ind] + V[ind] * V[ind] + W[ind] * W[ind];
			fc[nf * ind + p] = w[p] * (Rho[ind] * (3.0 * x + 9.0 / 2.0 * x * x - 3.0 / 2.0 * u2) + dRho[ind]);
			fcOld[nf * ind + p] = fc[nf * ind + p];
		}

	}
}

void BlockBasic::readInitCondition(int id, string simulPath) {
	string line;
	string fileName = simulPath + "init/blockInit" + std::to_string(id) + ".txt";
	try {
		ifstream* myfile = new ifstream(fileName);
		if (myfile->is_open()) {
			for (int i = 0; i < nAll; i++) {
				int ind = indAll[i];
				getline(*myfile, line);
				istringstream iss(line);
				vector<string> tokens{ istream_iterator<string>{iss}, istream_iterator<string>{} };
				Rho[ind] = stod(tokens[0]); // / Crho;
				U[ind] = stod(tokens[1]) / Cu;
				V[ind] = stod(tokens[2]) / Cu;
				W[ind] = stod(tokens[3]) / Cu;
				dRho[ind] = Rho[ind] - rho0;
			}
		}
		myfile->close();
		delete myfile;
	}
	catch (int ex) {
		cout << "Error in " << fileName << endl;
	}
}

void BlockBasic::computeInitDistribution() {
	for (int i = 0; i < nAll; i++) {
		int ind = indAll[i];
		for (int p = 0; p < nf; p++) {
			double x = ex[p] * U[ind] + ey[p] * V[ind] + ez[p] * W[ind];
			double u2 = U[ind] * U[ind] + V[ind] * V[ind] + W[ind] * W[ind];
			fc[nf * ind + p] = w[p] * (Rho[ind] * (3.0 * x + 9.0 / 2.0 * x * x - 3.0 / 2.0 * u2) + dRho[ind]);
		}
	}
}

void BlockBasic::writeBlock(int id) {
	ofstream myfile;
	myfile.open("results/results" + std::to_string(id) + ".txt", ios::out);
	myfile << ni << " " << nj << " " << nk << "\n";
	for (int i = 0; i < ni; i++) {
		for (int j = 0; j < nj; j++) {
			for (int k = 0; k < nk; k++) {
				int ind = (ni * nj) * k + ni * j + i;
				myfile << Rho[ind] << " " << U[ind] << " " << V[ind] << " " << W[ind] << " " << boundary[ind] << "\n";
			}
		}
	}
	myfile.close();
}

